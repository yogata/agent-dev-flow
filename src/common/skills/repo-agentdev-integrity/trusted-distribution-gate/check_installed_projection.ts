// Selection-aware installed projection checker.
//
// Verifies the placed/removed projection of an installed consumer root
// against the selection recorded in <root>/.agentdev/install-state.json
// (the install state record written by scripts/consumer/archive/install.ps1).
// The expected content is derived from the archive src/ tree passed via
// --source; per-root managed subsets mirror the installer's managed-rel
// contract (commands -> agentdev/**, skills/tools/agent-skills/senpi ->
// agentdev-*, plugins -> agentdev-* dirs + agentdev-*.ts loader shims, the
// agentdev-* whole-tree roots -> everything).
//
// CLI contract:
//   bun run check_installed_projection.ts --root <consumerRepoRoot>
//        [--source <archiveSrc>] [--json]
//   exit codes: 0 ok, 1 findings, 2 usage / pre-condition error (missing
//   --root, missing/unreadable/out-of-contract install state record).
//
// Finding categories:
//   missing_required_dir  a selected root directory is absent
//   projection_missing    an expected file (per --source) is not placed
//   content_mismatch      a placed file differs from its source content
//   extra                 managed-pattern content under a deselected root,
//                         or managed content a selected root must not have
//   broken_junction       a symlink / junction where a real file or
//                         directory is required (release installs are
//                         junction-free)

import * as fs from "fs";
import * as path from "path";
import { computeSha256 } from "./archive-builder.ts";

type Agent = "opencode" | "senpi" | "codex" | "antigravity";
const AGENTS: readonly Agent[] = ["opencode", "senpi", "codex", "antigravity"];

type RootKey =
  | "commands" | "skills" | "tools" | "plugins" | "senpi"
  | "agent-skills" | "agentdev-common" | "agentdev-senpi" | "agentdev-codex"
  | "agentdev-antigravity";

interface Finding {
  readonly category: string;
  readonly path: string;
  readonly detail: string;
}

interface RootSpec {
  readonly key: RootKey;
  /** Installed root, relative to the consumer repo root (forward slashes). */
  readonly rel: string;
  /** Absolute source dir; undefined = no content enumeration. */
  readonly source?: string;
  readonly kind: "commands" | "agentdevdirs" | "plugins" | "whole";
  readonly selected: boolean;
}

interface FileEntry {
  readonly rel: string;
  readonly abs: string;
  readonly sha256: string;
}

const SHIM_HEADER = "// Generated by scripts/install.ps1 / scripts/self-sync.ps1 - do not edit.\n";

function fail2(message: string): never {
  process.stderr.write(`check_installed_projection.ts: ${message}\n`);
  process.exit(2);
}

function canon(rel: string): string {
  return rel.replace(/\\/g, "/");
}

// Managed-subset predicate per copy-root key; mirrors the installer's
// Test-ManagedRootRel (backslashes normalized to forward slashes).
function isManagedRel(key: RootKey, rel: string): boolean {
  const first = rel.split("/")[0] ?? "";
  switch (key) {
    case "commands":
      return rel.startsWith("agentdev/");
    case "skills":
    case "tools":
    case "senpi":
    case "agent-skills":
    case "plugins":
      return first.startsWith("agentdev-");
    default:
      return true; // agentdev-* whole-tree roots
  }
}

function sha256Text(text: string): string {
  return computeSha256(new TextEncoder().encode(text));
}

function sha256File(abs: string): string {
  return computeSha256(new Uint8Array(fs.readFileSync(abs)));
}

function isReparsePoint(abs: string): boolean {
  try {
    fs.readlinkSync(abs);
    return true;
  } catch {
    return false;
  }
}

/**
 * Walk real files under dirAbs. node_modules is skipped (consumers run
 * dependency generation inside installed plugin packages; the archive never
 * ships it). Junctions / symlinks are reported via onReparse, not followed
 * (release installs are junction-free).
 */
function walkFiles(
  dirAbs: string,
  onReparse: (abs: string) => void,
): FileEntry[] {
  const out: FileEntry[] = [];
  const base = path.resolve(dirAbs);
  const stack: string[] = [base];
  while (stack.length > 0) {
    const current = stack.pop();
    if (current === undefined) break;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(current, { withFileTypes: true }) as fs.Dirent[];
    } catch {
      continue;
    }
    for (const ent of entries) {
      const full = path.join(current, ent.name);
      if (ent.isSymbolicLink()) {
        onReparse(full);
        continue;
      }
      if (ent.isDirectory()) {
        if (ent.name === "node_modules") continue;
        stack.push(full);
        continue;
      }
      if (ent.isFile()) {
        const rel = canon(path.relative(base, full));
        out.push({ rel, abs: full, sha256: sha256File(full) });
        continue;
      }
      // Entry kinds that are neither file nor symlink nor directory: treat
      // any readable link target as a reparse point (fail-closed).
      if (isReparsePoint(full)) onReparse(full);
    }
  }
  return out;
}

interface ExpectedEntry {
  readonly rel: string;
  readonly sha256: string | null;
}

// Expected rel -> sha256 map for a root, enumerated from the archive source
// tree (same root keys and kinds as the installer's Get-RootSourceFiles).
function expectedEntries(spec: RootSpec, onReparse: (abs: string) => void): ExpectedEntry[] {
  const src = spec.source;
  if (!src || !fs.existsSync(src)) return [];
  const out: ExpectedEntry[] = [];
  const relUnder = (abs: string): string => canon(path.relative(src, abs));
  const pushWalk = (dir: string): void => {
    for (const f of walkFiles(dir, onReparse)) {
      out.push({ rel: relUnder(f.abs), sha256: f.sha256 });
    }
  };
  let dirs: fs.Dirent[] = [];
  try {
    dirs = fs.readdirSync(src, { withFileTypes: true }) as fs.Dirent[];
  } catch {
    return out;
  }
  switch (spec.kind) {
    case "commands": {
      pushWalk(src);
      // Placed under .opencode/commands/agentdev/, so every expected rel
      // carries the agentdev/ prefix.
      for (let i = 0; i < out.length; i++) {
        out[i] = { rel: "agentdev/" + out[i]!.rel, sha256: out[i]!.sha256 };
      }
      break;
    }
    case "agentdevdirs": {
      for (const d of dirs) {
        if (!d.isDirectory() || !d.name.startsWith("agentdev-")) continue;
        pushWalk(path.join(src, d.name));
      }
      break;
    }
    case "plugins": {
      const pkgs = dirs.filter((d) => d.isDirectory() && d.name.startsWith("agentdev-"));
      for (const d of pkgs) pushWalk(path.join(src, d.name));
      for (const d of pkgs) {
        out.push({
          rel: `${d.name}.ts`,
          sha256: sha256Text(SHIM_HEADER + `export { default } from "./${d.name}/plugin.ts";\n`),
        });
      }
      break;
    }
    case "whole": {
      pushWalk(src);
      break;
    }
  }
  return out;
}

function main(): void {
  const args = process.argv.slice(2);
  let root: string | undefined;
  let source: string | undefined;
  const json = args.includes("--json");
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--root" && i + 1 < args.length) {
      root = args[++i];
    } else if (args[i] === "--source" && i + 1 < args.length) {
      source = args[++i];
    } else if (args[i] === "--json") {
      // handled above
    } else {
      fail2(`unexpected argument: ${args[i] ?? "(empty)"}`);
    }
  }
  if (!root) fail2("--root <consumerRepoRoot> is required");
  const rootAbs = path.resolve(root);
  if (!fs.existsSync(rootAbs) || !fs.statSync(rootAbs).isDirectory()) {
    fail2(`root is not a directory: ${rootAbs}`);
  }
  const sourceAbs = source ? path.resolve(source) : undefined;
  if (sourceAbs && (!fs.existsSync(sourceAbs) || !fs.statSync(sourceAbs).isDirectory())) {
    fail2(`source is not a directory: ${sourceAbs}`);
  }

  // This checker targets installs performed by
  // scripts/consumer/archive/install.ps1, which always writes a
  // selectedAgents install state record at <root>/.agentdev/.
  const recordPath = path.join(rootAbs, ".agentdev", "install-state.json");
  if (!fs.existsSync(recordPath)) {
    fail2(`install state record missing: ${recordPath}`);
  }
  let record: { selectedAgents?: unknown };
  try {
    record = JSON.parse(fs.readFileSync(recordPath, "utf-8"));
  } catch (e) {
    fail2(`install state record unreadable: ${(e as Error).message}`);
  }
  const rawAgents = record.selectedAgents;
  const selected = Array.isArray(rawAgents) ? rawAgents.map((a) => String(a)) : [];
  if (selected.length === 0 || !selected.every((a) => AGENTS.includes(a as Agent))) {
    fail2(
      "install state record has no valid selectedAgents (expected a non-empty subset of opencode|senpi|codex|antigravity)",
    );
  }

  const findings: Finding[] = [];
  const noteReparse = (base: string) => (abs: string): void => {
    findings.push({
      category: "broken_junction",
      path: canon(path.relative(base, abs)),
      detail: "symlink/junction where a real file or directory is required",
    });
  };

  const openSel = selected.includes("opencode");
  const senpiSel = selected.includes("senpi");
  const agentSideSel = selected.includes("codex") || selected.includes("antigravity");

  const specs: RootSpec[] = [
    { key: "commands", rel: ".opencode/commands", source: sourceAbs ? path.join(sourceAbs, "common", "commands", "agentdev") : undefined, kind: "commands", selected: openSel },
    { key: "skills", rel: ".opencode/skills", source: sourceAbs ? path.join(sourceAbs, "common", "skills") : undefined, kind: "agentdevdirs", selected: openSel },
    { key: "tools", rel: ".opencode/tools", source: sourceAbs ? path.join(sourceAbs, "common", "tools") : undefined, kind: "agentdevdirs", selected: openSel },
    { key: "plugins", rel: ".opencode/plugins", source: sourceAbs ? path.join(sourceAbs, "opencode", "plugins") : undefined, kind: "plugins", selected: openSel },
    { key: "senpi", rel: ".senpi/skills", source: sourceAbs ? path.join(sourceAbs, "common", "skills") : undefined, kind: "agentdevdirs", selected: senpiSel },
    { key: "agent-skills", rel: ".agents/skills", source: sourceAbs ? path.join(sourceAbs, "common", "skills") : undefined, kind: "agentdevdirs", selected: agentSideSel },
    { key: "agentdev-common", rel: ".agents/agentdev/common", source: sourceAbs ? path.join(sourceAbs, "common") : undefined, kind: "whole", selected: senpiSel || agentSideSel },
    { key: "agentdev-senpi", rel: ".agents/agentdev/senpi", source: sourceAbs ? path.join(sourceAbs, "senpi") : undefined, kind: "whole", selected: senpiSel },
    { key: "agentdev-codex", rel: ".agents/agentdev/codex", source: sourceAbs ? path.join(sourceAbs, "codex") : undefined, kind: "whole", selected: selected.includes("codex") },
    { key: "agentdev-antigravity", rel: ".agents/agentdev/antigravity", source: sourceAbs ? path.join(sourceAbs, "antigravity") : undefined, kind: "whole", selected: selected.includes("antigravity") },
  ];

  let expectedCount = 0;
  let placedCount = 0;
  for (const spec of specs) {
    const rootDirAbs = path.join(rootAbs, ...spec.rel.split("/"));
    const dirPresent = fs.existsSync(rootDirAbs) && fs.statSync(rootDirAbs).isDirectory();
    if (spec.selected) {
      if (!dirPresent) {
        findings.push({ category: "missing_required_dir", path: spec.rel, detail: `selected root '${spec.key}' is absent` });
        continue;
      }
      if (!spec.source) continue;
      const expected = new Map(expectedEntries(spec, noteReparse(rootDirAbs)).map((e) => [e.rel, e.sha256]));
      expectedCount += expected.size;
      const actual = walkFiles(rootDirAbs, noteReparse(rootDirAbs));
      placedCount += actual.length;
      const actualMap = new Map(actual.map((f) => [f.rel, f.sha256]));
      for (const [rel, sha] of expected) {
        const got = actualMap.get(rel);
        if (got === undefined) {
          findings.push({ category: "projection_missing", path: `${spec.rel}/${rel}`, detail: "expected file not placed" });
        } else if (sha !== null && got !== sha) {
          findings.push({ category: "content_mismatch", path: `${spec.rel}/${rel}`, detail: "placed content differs from source" });
        }
      }
      for (const f of actual) {
        if (isManagedRel(spec.key, f.rel) && !expected.has(f.rel)) {
          findings.push({ category: "extra", path: `${spec.rel}/${f.rel}`, detail: "managed content not present in the source tree" });
        }
      }
    } else if (dirPresent) {
      const actual = walkFiles(rootDirAbs, noteReparse(rootDirAbs));
      for (const f of actual) {
        if (isManagedRel(spec.key, f.rel)) {
          findings.push({ category: "extra", path: `${spec.rel}/${f.rel}`, detail: "managed content present under a deselected root" });
        }
      }
    }
  }

  const ok = findings.length === 0;
  const payload = {
    ok,
    root: canon(rootAbs),
    source: sourceAbs ? canon(sourceAbs) : null,
    selectedAgents: selected,
    stats: { expectedFiles: expectedCount, placedFiles: placedCount, roots: specs.length },
    findings,
  };
  if (json) {
    process.stdout.write(JSON.stringify(payload, null, 2) + "\n");
  } else {
    process.stdout.write("check_installed_projection.ts - installed projection (selection-aware)\n");
    process.stdout.write(`root: ${payload.root}\n`);
    process.stdout.write(`source: ${payload.source ?? "(none)"}\n`);
    process.stdout.write(`selectedAgents: ${selected.join(", ")}\n`);
    process.stdout.write(`ok: ${ok}\n`);
    process.stdout.write(`findings (${findings.length}):\n`);
    for (const f of findings) {
      process.stdout.write(`  [${f.category}] ${f.path}\n    ${f.detail}\n`);
    }
  }
  process.exit(ok ? 0 : 1);
}

main();
