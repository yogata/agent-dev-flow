// vendored engine bundle の生成スクリプト（bun run build:engine）。
//
// 1. package.json の dependencies（bun.lock 固定）から版情報を取り出す
// 2. build/engine-entry.ts を Bun.build で単一 ESM にバンドルする
// 3. base64 エンベロープ JSON（vendor/textlint-engine.bundle.json）へ書き出す
// 4. 配布境界検査の検出パターン（大文字前置詞 + 数字の ID、docs パス、
//    GitHub URL）が成果物に出現しないことを自己検証する
//
// バンドル後コードには焼き付き絶対パスの検出・無害化自己検査
// （build/absolute-path-guard.ts、runtime-package-boundary.md 契約）を適用する。
//
// 依存は配布前に解決した成果物として供給する（導入系スクリプトはネットワーク取得を
// 行わない）。node_modules を除外するアーカイブ経路でも本 bundle が同梱されるため、
// 空キャッシュ・ネットワーク遮断下で追加操作なしに起動できる。

import * as fs from "node:fs";
import * as path from "node:path";
import {
  guardEmbeddedAbsolutePaths,
  searchEmbeddedAbsolutePaths,
} from "./absolute-path-guard.ts";

const pluginDir = path.resolve(import.meta.dir, "..");
const packageJsonPath = path.join(pluginDir, "package.json");
const entryPath = path.join(pluginDir, "build", "engine-entry.ts");
const outDir = path.join(pluginDir, "vendor");
const outJsonPath = path.join(outDir, "textlint-engine.bundle.json");

const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, "utf8")) as {
  dependencies?: Record<string, string>;
};

// 1) lockfile 固定版の読み取り（bun.lock の text lockfile から直接パッケージ版を引く）
const versions: Record<string, string> = {};
const lockPath = path.join(pluginDir, "bun.lock");
const lockText = fs.readFileSync(lockPath, "utf8");
for (const name of Object.keys(packageJson.dependencies ?? {})) {
  // bun.lock v1 のパッケージ行: "pkg@ver" 形式（scoped は @scope/pkg@ver）
  const escaped = name.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\//g, "\\/");
  const re = new RegExp(`"?${escaped}@([0-9][^"\\s,)]*)"`);
  const m = lockText.match(re);
  if (m === null || m[1] === undefined) {
    throw new Error(`cannot find pinned version of ${name} in bun.lock`);
  }
  versions[name] = m[1];
}

// 2) バンドル（minify。target node: 実行時の Bun / Node 両方で読める単一 ESM。
//    target bun が付与する「// @bun」バナーは Bun の変換済み扱いの高速経路を
//    トリガーし、多バイト識別子（採用規則の日本語識別子）の構文解析を破損させる
//    ため付与しない（banner が残っていれば除去する））
const build = await Bun.build({
  entrypoints: [entryPath],
  target: "node",
  format: "esm",
  minify: true,
  naming: { entry: "[dir]/[name].[ext]" },
  define: {
    "globalThis.__ADF_ENGINE_VERSIONS__": JSON.stringify(versions),
  },
});
if (!build.success) {
  for (const log of build.logs) console.error(log);
  throw new Error("Bun.build failed");
}
const artifact = build.outputs.find((o) => o.kind === "entry-point");
if (artifact === undefined) throw new Error("Bun.build produced no entry-point output");
let code = (await artifact.text()).replace(/^\/\/ @bun\r?\n/, "");

// kuromojin 既定 dicPath 用 require.resolve 等がビルド時の絶対パス（worktree パスを
// 含む）として焼き付く既知現象への自己検査。buildRoot 配下のパスは相対パスへ無害化
// してから出力し、無害化不能なパスが残る場合は build を fail させる（fail-closed）。
const guard = guardEmbeddedAbsolutePaths(code, pluginDir);
for (const s of guard.sanitized) {
  console.log(`sanitized embedded absolute path -> ${s.to}`);
}
if (guard.unresolved.length > 0) {
  for (const u of guard.unresolved) {
    console.error(
      `embedded absolute path cannot be sanitized (not under ${pluginDir}): ${u.decoded}`,
    );
  }
  throw new Error(
    `generated bundle embeds ${guard.unresolved.length} absolute path(s) that cannot be sanitized`,
  );
}
code = guard.code;
const residual = searchEmbeddedAbsolutePaths(code);
if (residual.length > 0) {
  for (const r of residual) {
    console.error(`embedded absolute path remains after sanitization: ${r.decoded}`);
  }
  throw new Error("generated bundle still embeds absolute path(s) after sanitization");
}

// 3) base64 エンベロープの書き出し（UTF-8 no BOM / LF）
fs.mkdirSync(outDir, { recursive: true });
const codeBase64 = Buffer.from(code, "utf8").toString("base64");
const envelope = {
  schema: 1,
  description:
    "Vendored (pre-resolved) textlint engine bundle for agentdev-textlint-guard. Generated by build/build-engine.ts from package.json dependencies pinned by bun.lock. Do not edit.",
  versions,
  codeBase64,
};
const jsonText = `${JSON.stringify(envelope, null, 1)}\n`;

// 4) 配布境界パターンの自己検証（base64 部はアルファベット+数字+/+= のみで
//    ハイフンを含まないため ID パターンと URL パターンに構造上一致しない。
//    エンベロープのメタ情報にもこれらのパターンを出さない）
const ID_PATTERN = /\b([A-Z]{2,})-(\d{1,})\b/g;
const DOCS_PATH_PATTERN = /docs[\\/](?:adr|requirements|specs|decisions)[\\/][^\s)\]\|\\"'`<>{}?#]+/g;
const URL_PATTERN = /(?:github\.com\/[A-Za-z0-9_-]+\/[A-Za-z0-9_.-]+\/(?:blob|raw)\/|raw\.githubusercontent\.com\/)/i;
for (const [label, pattern] of [
  ["concrete-id", ID_PATTERN],
  ["docs-path", DOCS_PATH_PATTERN],
] as const) {
  const hits = jsonText.match(pattern);
  if (hits !== null) {
    throw new Error(`generated bundle matches the distribution-boundary ${label} pattern: ${hits[0]}`);
  }
}
if (URL_PATTERN.test(jsonText)) {
  throw new Error("generated bundle matches the distribution-boundary fixed-url pattern");
}

fs.writeFileSync(outJsonPath, jsonText, "utf8");
const sizeKb = Math.round(jsonText.length / 1024);
console.log(`engine bundle written: ${path.relative(pluginDir, outJsonPath)} (${sizeKb} KB)`);
console.log("versions:", JSON.stringify(versions));

// 5) kuromoji 辞書の同梱（vendor/kuromoji-dict/）。
//    採用プリセットの形態素規則は kuromojin 経由で kuromoji 辞書を必要とする。
//    kuromojin の既定 dicPath は node_modules 内を指すため、導入先の
//    node_modules 有無に依存しないよう、配布物として辞書を実ファイルで同梱する
//    （実行時は lib/engine-bundle.ts が KUROMOJIN_DIC_PATH を本配置へ固定する）。
const dictSrcDir = path.join(pluginDir, "node_modules", "kuromoji", "dict");
const dictOutDir = path.join(outDir, "kuromoji-dict");
if (!fs.existsSync(dictSrcDir)) {
  throw new Error(`kuromoji dict not found at ${dictSrcDir}; run bun install before build:engine`);
}
fs.rmSync(dictOutDir, { recursive: true, force: true });
fs.mkdirSync(dictOutDir, { recursive: true });
for (const name of fs.readdirSync(dictSrcDir)) {
  fs.copyFileSync(path.join(dictSrcDir, name), path.join(dictOutDir, name));
}
const dictFiles = fs.readdirSync(dictOutDir);
if (dictFiles.length === 0) {
  throw new Error(`kuromoji dict copy produced no files at ${dictOutDir}`);
}
console.log(`kuromoji dict copied: ${dictOutDir} (${dictFiles.length} files)`);
